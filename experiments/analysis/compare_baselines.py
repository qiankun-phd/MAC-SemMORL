"""Cross-method comparison of Issue #8 baseline results.

Reads npz files written by ``scripts/run_baseline.py`` (schema in
``docs/DESIGN-baselines.md`` §3) and produces:

    1. Comparison table (text + CSV) — final HV / UT / sparsity / wallclock
       per (method, config), seed-mean ± std.
    2. Pareto-front scatter plot — per-objective scatter of every method's
       final-EP points, useful for the journal experiments figure.
    3. Constraint-violation table for the constrained methods only.

Lives in ``experiments/analysis/`` to match the existing analysis pipeline
(``analyze_results.py``, ``check_progress.py``, etc.). Reads through the
``baselines.result_loader`` module so the schema is the single source of
truth.

Usage:
    PYTHONPATH=. python experiments/analysis/compare_baselines.py \\
        --results_dir results --output_dir experiments/analysis/compare_out

    # Anchor-config only:
    python experiments/analysis/compare_baselines.py \\
        --results_dir results --M 2 --K 5 --mobility none

The script is read-only on the npz inputs; it writes outputs to
``--output_dir``.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from typing import List, Optional

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from baselines import ResultGroup, load_results_dir  # noqa: E402


def _filter_groups(
    groups: List[ResultGroup],
    M: Optional[int],
    K: Optional[int],
    mobility: Optional[str],
    channel: Optional[str],
    perturbation: Optional[str],
) -> List[ResultGroup]:
    out = []
    for g in groups:
        if M is not None and g.M != M:
            continue
        if K is not None and g.K != K:
            continue
        if mobility is not None and g.mobility != mobility:
            continue
        if channel is not None and g.channel != channel:
            continue
        if perturbation is not None and g.perturbation != perturbation:
            continue
        out.append(g)
    return out


def write_comparison_table(groups: List[ResultGroup], out_path: str) -> None:
    """Write the (method, config) summary table as both Markdown and CSV.

    Writes ``out_path`` (markdown) and ``out_path[:-3] + '.csv'`` (csv).
    """
    rows = []
    for g in sorted(
        groups,
        key=lambda g: (g.M, g.K, g.method, g.constraint_handler),
    ):
        hv_mean, hv_std = g.final_hv_mean_std()
        ut_mean, ut_std = g.final_ut_mean_std()
        # Per-objective seed mean + std at the final eval.
        obj_stack = g.final_obj_means_stacked()  # (n_seeds, N)
        obj_mean = obj_stack.mean(axis=0) if obj_stack.size else np.full(4, np.nan)
        obj_std = obj_stack.std(axis=0) if obj_stack.size else np.full(4, np.nan)
        rows.append({
            "method": g.method,
            "M": g.M, "K": g.K,
            "mobility": g.mobility,
            "constr": g.constraint_handler,
            "n_seeds": g.n_seeds,
            "hv_mean": hv_mean, "hv_std": hv_std,
            "ut_mean": ut_mean, "ut_std": ut_std,
            "fid_mean": float(obj_mean[0]),
            "aosi_mean": float(obj_mean[1]),
            "ener_mean": float(obj_mean[2]),
            "jain_mean": float(obj_mean[3]),
        })

    # CSV output
    csv_path = out_path[:-3] + ".csv" if out_path.endswith(".md") else out_path + ".csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(
            f,
            fieldnames=[
                "method", "M", "K", "mobility", "constr", "n_seeds",
                "hv_mean", "hv_std", "ut_mean", "ut_std",
                "fid_mean", "aosi_mean", "ener_mean", "jain_mean",
            ],
        )
        w.writeheader()
        for r in rows:
            w.writerow(r)

    # Markdown output
    with open(out_path, "w") as f:
        f.write("# Baseline comparison\n\n")
        f.write(f"Generated by `experiments/analysis/compare_baselines.py`. "
                f"{len(rows)} (method, config) groups across "
                f"{sum(r['n_seeds'] for r in rows)} runs total.\n\n")
        f.write(
            "| method | M | K | mob | constr | seeds | "
            "HV (mean ± std) | UT | Fid | AoSI | Ener | Jain |\n"
        )
        f.write(
            "|--------|---|---|-----|--------|-------|"
            "-----------------|----|-----|------|------|------|\n"
        )
        for r in rows:
            f.write(
                f"| {r['method']} | {r['M']} | {r['K']} | {r['mobility']} | "
                f"{r['constr']} | {r['n_seeds']} | "
                f"{r['hv_mean']:.2e} ± {r['hv_std']:.2e} | "
                f"{r['ut_mean']:.1f} | "
                f"{r['fid_mean']:.1f} | {r['aosi_mean']:.1f} | "
                f"{r['ener_mean']:.1f} | {r['jain_mean']:.1f} |\n"
            )


def write_violation_table(groups: List[ResultGroup], out_path: str) -> None:
    """Constrained methods only — c_1 / c_2 / c_3 violation rates."""
    rows = []
    for g in sorted(groups, key=lambda g: (g.method, g.M)):
        # Filter to seeds that actually populated violation rates.
        vio_rates = np.stack(
            [r.c_violation_rates for r in g.runs]
        ) if g.runs else np.zeros((0, 3))
        if vio_rates.size == 0 or np.all(np.isnan(vio_rates)):
            continue
        with np.errstate(invalid="ignore"):
            mean = np.nanmean(vio_rates, axis=0)
            std = np.nanstd(vio_rates, axis=0)
        rows.append({
            "method": g.method, "M": g.M, "K": g.K,
            "constr": g.constraint_handler,
            "c1_aosi_tail_mean": float(mean[0]), "c1_std": float(std[0]),
            "c2_energy_budget_mean": float(mean[1]), "c2_std": float(std[1]),
            "c3_service_rate_mean": float(mean[2]), "c3_std": float(std[2]),
        })
    if not rows:
        with open(out_path, "w") as f:
            f.write("# Constraint violation rates\n\n"
                    "_No runs with populated `c_violation_rates` found._\n")
        return
    with open(out_path, "w") as f:
        f.write("# Constraint violation rates (constrained methods only)\n\n")
        f.write(
            "| method | M | K | constr | "
            "c1 AoSI-tail | c2 energy-budget | c3 service-rate |\n"
        )
        f.write(
            "|--------|---|---|--------|"
            "-------------|-----------------|-----------------|\n"
        )
        for r in rows:
            f.write(
                f"| {r['method']} | {r['M']} | {r['K']} | {r['constr']} | "
                f"{r['c1_aosi_tail_mean']:.3f} ± {r['c1_std']:.3f} | "
                f"{r['c2_energy_budget_mean']:.3f} ± {r['c2_std']:.3f} | "
                f"{r['c3_service_rate_mean']:.3f} ± {r['c3_std']:.3f} |\n"
            )


def write_pareto_plot(
    groups: List[ResultGroup],
    out_path: str,
    obj_x: int = 0,
    obj_y: int = 2,
) -> None:
    """2D scatter of every method's final-EP points on (obj_x, obj_y).
    Defaults to (Fid, Energy) which is the most informative pair for
    UAV-SemCom papers."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        # Fallback: write a placeholder note if matplotlib isn't available.
        with open(out_path + ".txt", "w") as f:
            f.write("matplotlib not installed; skipping Pareto plot. "
                    "Install via `pip install matplotlib` and re-run.\n")
        return

    obj_names = ["Fid", "AoSI", "Energy", "Jain"]
    plt.figure(figsize=(8, 6))
    colors = plt.cm.tab10.colors
    for i, g in enumerate(sorted(groups, key=lambda g: g.method)):
        pts = g.all_final_ep_objs()  # (P_total, N)
        if pts.size == 0:
            continue
        plt.scatter(
            pts[:, obj_x], pts[:, obj_y],
            color=colors[i % len(colors)],
            label=f"{g.method} (M={g.M},K={g.K},seeds={g.n_seeds})",
            alpha=0.6, s=18,
        )
    plt.xlabel(obj_names[obj_x])
    plt.ylabel(obj_names[obj_y])
    plt.title("Pareto-front comparison across methods")
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=8, loc="best")
    plt.tight_layout()
    plt.savefig(out_path, dpi=140)
    plt.close()


def main():
    p = argparse.ArgumentParser(description="Issue #8 baseline comparison")
    p.add_argument("--results_dir", default="results")
    p.add_argument("--output_dir", default="experiments/analysis/compare_out")
    p.add_argument("--method_filter", nargs="+", default=None,
                   help="Restrict to these baseline names (default: all).")
    p.add_argument("--M", type=int, default=None)
    p.add_argument("--K", type=int, default=None)
    p.add_argument("--mobility", type=str, default=None)
    p.add_argument("--channel", type=str, default=None)
    p.add_argument("--perturbation", type=str, default=None)
    p.add_argument("--obj_x", type=int, default=0,
                   help="Pareto plot x-axis objective index (0=Fid, 2=Energy)")
    p.add_argument("--obj_y", type=int, default=2)
    args = p.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    groups = load_results_dir(args.results_dir, method_filter=args.method_filter)
    groups = _filter_groups(groups, args.M, args.K, args.mobility,
                            args.channel, args.perturbation)
    if not groups:
        print(f"No results matched filters in {args.results_dir!r}.", file=sys.stderr)
        return 1

    print(f"Loaded {len(groups)} (method, config) groups, "
          f"{sum(g.n_seeds for g in groups)} runs total.")

    table_path = os.path.join(args.output_dir, "comparison_table.md")
    write_comparison_table(groups, table_path)
    print(f"  wrote {table_path}")
    print(f"  wrote {table_path[:-3] + '.csv'}")

    vio_path = os.path.join(args.output_dir, "violation_table.md")
    write_violation_table(groups, vio_path)
    print(f"  wrote {vio_path}")

    plot_path = os.path.join(args.output_dir, "pareto_front.png")
    write_pareto_plot(groups, plot_path, args.obj_x, args.obj_y)
    print(f"  wrote {plot_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
